export async function seedModule1Content(prisma: PrismaClient) {
  const module1 = await prisma.module.findFirst({
    where: { slug: "module-1" },
    include: { lessons: { orderBy: { position: "asc" } }, assignments: true, course: true },
  });
  if (!module1) {
    throw new Error("Module module-1 not found — run full seed first");
  }

  await prisma.module.update({
    where: { id: module1.id },
    data: {
      title: "Знакомство с AutoZap",
      description:
        "Целостное понимание продукта, возможностей, аудитории и ценности для бизнеса.",
      status: "PUBLISHED",
    },
  });

  for (let i = 0; i < LESSONS.length; i++) {
    const lessonDef = LESSONS[i];
    const existing = module1.lessons.find((l) => l.slug === lessonDef.slug);
    if (existing) {
      await prisma.lesson.update({
        where: { id: existing.id },
        data: {
          title: lessonDef.title,
          position: i + 1,
          estimatedMinutes: lessonDef.estimatedMinutes,
          content: lessonDef.content,
          status: "PUBLISHED",
        },
      });
    } else {
      await prisma.lesson.create({
        data: {
          moduleId: module1.id,
          slug: lessonDef.slug,
          title: lessonDef.title,
          position: i + 1,
          estimatedMinutes: lessonDef.estimatedMinutes,
          content: lessonDef.content,
          status: "PUBLISHED",
        },
      });
    }
  }

  // Soft-retire old lessons beyond the new set (e.g. if titles/slugs drifted)
  const keepSlugs = new Set(LESSONS.map((l) => l.slug));
  for (const lesson of module1.lessons) {
    if (!keepSlugs.has(lesson.slug)) {
      await prisma.lesson.update({
        where: { id: lesson.id },
        data: { status: "DRAFT" },
      });
    }
  }

  await prisma.moduleAssessment.upsert({
    where: { moduleId: module1.id },
    create: {
      moduleId: module1.id,
      title: "Финальная проверка — Модуль 1",
      passScore: 70,
      content: ASSESSMENT,
    },
    update: {
      title: "Финальная проверка — Модуль 1",
      passScore: 70,
      content: ASSESSMENT,
    },
  });

  const assignment = module1.assignments[0];
  if (assignment) {
    await prisma.assignment.update({
      where: { id: assignment.id },
      data: {
        title: "Объясни своими словами — Модуль 1",
        description:
          "Свободный ответ из финальной проверки. Куратор проверяет понимание AutoZap как автомобильного маркетплейса с торговыми, логистическими и финансовыми возможностями.",
      },
    });
  }

  const LESSON_AZ = 5;
  const CLEAN_BONUS_AZ = 1;
  const QUALITY_CAP_AZ = 2;
  const ASSIGNMENT_MAX_AZ = 10;
  const ASSIGNMENT_RANGES = [
    { label: "Слабо", minAz: 3, maxAz: 4, criteria: "Ответ есть, но поверхностно", sortOrder: 0 },
    { label: "Средне", minAz: 5, maxAz: 7, criteria: "Основные идеи поняты", sortOrder: 1 },
    {
      label: "Хорошо",
      minAz: 8,
      maxAz: 10,
      criteria: "Полное понимание продукта и подбора возможностей",
      sortOrder: 2,
    },
  ];

  const qualityLessonSlugs = new Set(["lesson-4", "lesson-5", "lesson-8"]);

  const admin = await prisma.user.findFirst({ where: { role: "ADMIN" } });
  const { AZService } = await import("../server/az/az-service");
  const az = new AZService(prisma);
  const lessons = await prisma.lesson.findMany({
    where: { moduleId: module1.id, status: "PUBLISHED" },
    orderBy: { position: "asc" },
  });

  async function ensureRule(params: {
    actionType: "LESSON_COMPLETED" | "CUSTOM" | "ASSIGNMENT_REVIEWED";
    scopeType: "LESSON" | "MODULE";
    lessonId?: string;
    name: string;
    maxAz: number;
    allowsPartial?: boolean;
    qualityDependent?: boolean;
    qualityRanges?: typeof ASSIGNMENT_RANGES;
  }) {
    const existing = await prisma.azRewardRule.findFirst({
      where: {
        actionType: params.actionType,
        active: true,
        ...(params.lessonId ? { lessonId: params.lessonId } : { moduleId: module1.id, lessonId: null }),
        ...(params.actionType === "CUSTOM" && params.lessonId ? { name: params.name } : {}),
      },
      include: { versions: { where: { active: true }, orderBy: { version: "desc" }, take: 1 } },
    });

    if (!existing) {
      await az.createRewardRule({
        actionType: params.actionType,
        scopeType: params.scopeType,
        courseId: module1.courseId,
        moduleId: module1.id,
        lessonId: params.lessonId,
        name: params.name,
        maxAz: params.maxAz,
        allowsPartial: params.allowsPartial ?? false,
        allowsRepeat: false,
        qualityDependent: params.qualityDependent ?? false,
        qualityRanges: params.qualityRanges,
        createdById: admin?.id,
      });
      return;
    }

    if (existing.versions[0]?.maxAz !== params.maxAz) {
      await az.publishRewardRuleVersion({
        ruleId: existing.id,
        maxAz: params.maxAz,
        allowsPartial: params.allowsPartial ?? false,
        allowsRepeat: false,
        qualityDependent: params.qualityDependent ?? false,
        qualityRanges: params.qualityRanges,
        applyMode: "FUTURE_ONLY",
        createdById: admin?.id,
        note: "Module 1 earning model sync",
      });
    }
  }

  for (let i = 0; i < lessons.length; i++) {
    const lesson = lessons[i];
    if ((lesson.estimatedMinutes ?? 0) <= 5) {
      await prisma.lesson.update({
        where: { id: lesson.id },
        data: { estimatedMinutes: 6 },
      });
    }

    await ensureRule({
      actionType: "LESSON_COMPLETED",
      scopeType: "LESSON",
      lessonId: lesson.id,
      name: `Module 1 / Lesson ${i + 1} completion`,
      maxAz: LESSON_AZ,
    });

    const bonusCap = qualityLessonSlugs.has(lesson.slug)
      ? CLEAN_BONUS_AZ + QUALITY_CAP_AZ
      : CLEAN_BONUS_AZ;
    await ensureRule({
      actionType: "CUSTOM",
      scopeType: "LESSON",
      lessonId: lesson.id,
      name: `Module 1 / Lesson ${i + 1} clean & quality`,
      maxAz: bonusCap,
      allowsPartial: true,
    });
  }

  await ensureRule({
    actionType: "ASSIGNMENT_REVIEWED",
    scopeType: "MODULE",
    name: "Module 1 practice assignment",
    maxAz: ASSIGNMENT_MAX_AZ,
    allowsPartial: true,
    qualityDependent: true,
    qualityRanges: ASSIGNMENT_RANGES,
  });

  const activityRule = await prisma.azRewardRule.findFirst({
    where: { actionType: "CUSTOM", scopeType: "GLOBAL", name: "Activity board award", active: true },
  });
  if (!activityRule) {
    await az.createRewardRule({
      actionType: "CUSTOM",
      scopeType: "GLOBAL",
      name: "Activity board award",
      maxAz: 5,
      allowsPartial: true,
      allowsRepeat: true,
      qualityDependent: false,
      createdById: admin?.id,
    });
  }

  return {
    moduleId: module1.id,
    lessons: LESSONS.length,
    lessonAz: LESSON_AZ,
    cleanBonus: CLEAN_BONUS_AZ,
    qualityCap: QUALITY_CAP_AZ,
    assignmentAz: "3-10",
  };
}

/** Standalone: npm run db:seed:module1 */
export async function runSeedModule1Standalone() {
  const { PrismaClient } = await import("@prisma/client");
  const prisma = new PrismaClient();
  try {
    const result = await seedModule1Content(prisma);
    console.log("Module 1 content seeded:", result);
  } finally {
    await prisma.$disconnect();
  }
}

const isDirect =
  typeof process !== "undefined" &&
  process.argv[1] &&
  (process.argv[1].endsWith("seed-module1.ts") || process.argv[1].endsWith("seed-module1.js"));

if (isDirect) {
  runSeedModule1Standalone().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
